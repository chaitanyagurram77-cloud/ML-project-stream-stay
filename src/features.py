"""StreamStay Feature Engineering and Pipeline module.
Implements shared scikit-learn transformers and pipelines to ensure zero training-serving skew.
"""

from typing import List, Tuple, Dict, Any, Optional
import numpy as np
import pandas as pd
from sklearn.base import BaseEstimator, TransformerMixin
from sklearn.compose import ColumnTransformer
from sklearn.impute import SimpleImputer
from sklearn.preprocessing import StandardScaler, OneHotEncoder
from sklearn.pipeline import Pipeline
from sklearn.model_selection import train_test_split


NUMERICAL_FEATURES = [
    "tenure_months",
    "avg_weekly_watch_hours",
    "sessions_per_week",
    "payment_failures",
    "support_tickets",
    "last_login_days_ago",
]

CATEGORICAL_FEATURES = [
    "plan_type",
    "device",
    "top_genre",
]

CLASSIFICATION_TARGET = "churned"
REGRESSION_TARGET = "next_month_watch_hours"
ID_COLUMN = "user_id"


def build_preprocessor(include_missing_indicator: bool = True) -> ColumnTransformer:
    """
    Construct a scikit-learn ColumnTransformer that applies:
    - Median imputation with MissingIndicator for numerical features
    - Standard scaling for numerical features
    - Most-frequent imputation and One-Hot Encoding for categorical features
    
    This exact pipeline is shared across training, offline evaluation, and serving API
    to eliminate training-serving skew.
    """
    num_pipeline = Pipeline([
        ("imputer", SimpleImputer(strategy="median", add_indicator=include_missing_indicator)),
        ("scaler", StandardScaler()),
    ])

    cat_pipeline = Pipeline([
        ("imputer", SimpleImputer(strategy="most_frequent")),
        ("onehot", OneHotEncoder(handle_unknown="ignore", sparse_output=False)),
    ])

    preprocessor = ColumnTransformer(
        transformers=[
            ("num", num_pipeline, NUMERICAL_FEATURES),
            ("cat", cat_pipeline, CATEGORICAL_FEATURES),
        ],
        remainder="drop",
        verbose_feature_names_out=False,
    )
    return preprocessor


def get_feature_names_from_preprocessor(preprocessor: ColumnTransformer) -> List[str]:
    """
    Retrieve feature names generated by the fitted ColumnTransformer.
    Handles numeric names, missing indicators, and one-hot categories.
    """
    feature_names = []
    for name, trans, cols in preprocessor.transformers_:
        if name == "remainder":
            continue
        if hasattr(trans, "get_feature_names_out"):
            try:
                names = list(trans.get_feature_names_out(cols))
                feature_names.extend(names)
                continue
            except Exception:
                pass
        # Fallback inspection for nested pipelines
        if hasattr(trans, "named_steps"):
            last_step = list(trans.named_steps.values())[-1]
            if hasattr(last_step, "get_feature_names_out"):
                try:
                    names = list(last_step.get_feature_names_out(cols))
                    feature_names.extend(names)
                    continue
                except Exception:
                    pass
        # Default column list
        feature_names.extend([str(c) for c in cols])
    return feature_names


def split_streamstay_data(
    df: pd.DataFrame,
    test_size: float = 0.15,
    val_size: float = 0.15,
    random_seed: int = 42
) -> Dict[str, pd.DataFrame]:
    """
    Stratified split into Train, Validation, and Test sets.
    The test set remains completely untouched until final evaluation.
    
    Returns
    -------
    dict:
        {
            'train': pd.DataFrame,
            'val': pd.DataFrame,
            'test': pd.DataFrame
        }
    """
    stratify_col = df[CLASSIFICATION_TARGET]

    # First split off the test set
    df_train_val, df_test = train_test_split(
        df,
        test_size=test_size,
        stratify=stratify_col,
        random_state=random_seed
    )

    # Then split train into train and val
    relative_val_size = val_size / (1.0 - test_size)
    stratify_train_val = df_train_val[CLASSIFICATION_TARGET]

    df_train, df_val = train_test_split(
        df_train_val,
        test_size=relative_val_size,
        stratify=stratify_train_val,
        random_state=random_seed
    )

    return {
        "train": df_train.reset_index(drop=True),
        "val": df_val.reset_index(drop=True),
        "test": df_test.reset_index(drop=True),
    }


class ClusterFeatureAugmenter(BaseEstimator, TransformerMixin):
    """
    Scikit-learn compatible transformer that assigns K-Means cluster
    labels to incoming data and returns one-hot encoded cluster indicators.
    Prevents leakage by fitting only on training data.
    """
    def __init__(self, n_clusters: int = 3, random_state: int = 42):
        self.n_clusters = n_clusters
        self.random_state = random_state
        self.kmeans = None

    def fit(self, X, y=None):
        from sklearn.cluster import KMeans
        self.kmeans = KMeans(
            n_clusters=self.n_clusters,
            random_state=self.random_state,
            n_init=10
        )
        self.kmeans.fit(X)
        return self

    def transform(self, X):
        cluster_ids = self.kmeans.predict(X)
        # One-hot encode clusters
        n_samples = X.shape[0]
        one_hot = np.zeros((n_samples, self.n_clusters), dtype=float)
        for i, c in enumerate(cluster_ids):
            one_hot[i, c] = 1.0
        return np.hstack([X, one_hot])
